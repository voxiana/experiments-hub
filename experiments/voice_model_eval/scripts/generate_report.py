"""
Generate a markdown leaderboard from a run summary.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate markdown leaderboard report")
    parser.add_argument(
        "--summary",
        required=True,
        help="Path to summary.json generated by run_eval.py",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Optional output markdown path. Defaults to leaderboard.md next to summary.",
    )
    return parser.parse_args()


def build_markdown(summary: dict) -> str:
    leaderboard = summary.get("leaderboard", [])
    lines = [
        "# Voice Model Evaluation Report",
        "",
        f"Total evaluated cases: {summary.get('total_cases', 0)}",
        "",
        "| backend_id | runs | success_rate | latency_p50_ms | latency_p95_ms | avg_real_time_factor | contract_compatibility_rate |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for row in leaderboard:
        lines.append(
            "| {backend_id} | {runs} | {success_rate:.2%} | {latency_p50_ms:.2f} | "
            "{latency_p95_ms:.2f} | {avg_real_time_factor:.3f} | {compat} |".format(
                backend_id=row.get("backend_id", ""),
                runs=row.get("runs", 0),
                success_rate=row.get("success_rate", 0.0),
                latency_p50_ms=row.get("latency_p50_ms", 0.0),
                latency_p95_ms=row.get("latency_p95_ms", 0.0),
                avg_real_time_factor=row.get("avg_real_time_factor", 0.0),
                compat=(
                    "n/a"
                    if row.get("baseline_contract_compatibility_rate") is None
                    else f"{row['baseline_contract_compatibility_rate']:.2%}"
                ),
            )
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    args = parse_args()
    summary_path = Path(args.summary)
    with summary_path.open("r", encoding="utf-8") as file_handle:
        summary = json.load(file_handle)

    markdown = build_markdown(summary)
    output_path = Path(args.output) if args.output else summary_path.with_name("leaderboard.md")
    output_path.write_text(markdown, encoding="utf-8")
    print(f"Leaderboard report written: {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

